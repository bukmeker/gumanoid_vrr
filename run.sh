#!/bin/bash
# run.sh
# =======
# Скрипт быстрого запуска G1 Avatar Controller.
# Запускать каждый раз перед сеансом управления роботом.
#
# Использование:
#   ./run.sh [сетевой_интерфейс]
#   ./run.sh eth0          # по умолчанию
#   ./run.sh enp3s0        # если Ethernet на другом интерфейсе
#
# Автор: Андреюк М.О., Жук Б.Д. (Группа ИИ-25, БрГТУ, 2026)

set -e

INTERFACE="${1:-eth0}"
PROJECT_DIR="$HOME/g1_avatar_project"
ROBOT_IP="192.168.123.161"

echo "============================================================"
echo "  G1 EDU Avatar Controller"
echo "  Интерфейс: $INTERFACE"
echo "============================================================"

# ─── Проверка связи с роботом ────────────────────────────────────────────
echo ""
echo "[1/3] Проверка связи с роботом ($ROBOT_IP)..."
if ping -c 2 -W 1 "$ROBOT_IP" &>/dev/null; then
    echo "  Робот доступен."
else
    echo "  ОШИБКА: Робот недоступен на $ROBOT_IP"
    echo "  Проверьте:"
    echo "    - Ethernet-кабель подключён"
    echo "    - IP вашего ПК: 192.168.123.222"
    echo "    - Маска: 255.255.255.0"
    exit 1
fi

# ─── Активация окружения ──────────────────────────────────────────────────
echo ""
echo "[2/3] Активация виртуального окружения..."
cd "$PROJECT_DIR"
source venv/bin/activate
export CYCLONEDDS_HOME="$HOME/cyclonedds/install"

# ─── Запуск контроллера ───────────────────────────────────────────────────
echo ""
echo "[3/3] Запуск контроллера..."
echo "  Для остановки нажмите Ctrl+C"
echo "============================================================"
echo ""

python3 g1_avatar_controller.py "$INTERFACE"
